    source              text NOT NULL,
    lot_number          text NOT NULL,
    yard_code           text,
    yard_name           text,
    sale_date           date,
    sale_at             timestamptz,
    vehicle_type        text,
    year                integer,
    make                text,
    model_group         text,
    model_detail        text,
    trim                text,
    body_style          text,
    color               text,
    damage_primary      text,
    damage_secondary    text,
    title_state         text,
    title_type          text,
    has_keys            text,
    vin                 text,
    odometer            numeric,
    odometer_brand      text,
    est_retail_value    numeric,
    repair_cost         numeric,
    engine              text,
    drive               text,
    transmission        text,
    fuel_type           text,
    cylinders           text,
    runs_drives         text,
    sale_status         text,
    high_bid            numeric,
    buy_it_now_price    numeric,
    currency            text,
    location_city       text,
    location_state      text,
    location_zip        text,
    location_country    text,
    seller_name         text,
    image_url           text,
    thumbnail_url       text,
    source_created_at   timestamp,
    source_updated_at   timestamptz,
    attributes          jsonb NOT NULL,
    row_hash            bytea NOT NULL,
    first_seen_at       timestamptz NOT NULL,
    last_seen_at        timestamptz NOT NULL,
    last_changed_at     timestamptz NOT NULL,
    removed_at          timestamptz,
    first_file_id       bigint,
    last_file_id        bigint,
